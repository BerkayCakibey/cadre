"""Language helpers and message catalog for operator-facing text."""
from __future__ import annotations

import os
from pathlib import Path

DILLER = ('tr', 'en')
DIL = 'tr'
EKSIK: set[str] = set()


def ev() -> Path:
    return Path(os.environ.get('CADRE_HOME') or Path.home() / '.local/share/cadre-engineering')


def dosya() -> Path:
    return ev() / 'arayuz-dil'


def oku() -> str:
    secim = os.environ.get('CADRE_DIL', '').strip().lower()
    if secim not in DILLER:
        try:
            secim = dosya().read_text().strip().lower()
        except (OSError, UnicodeError):
            secim = ''
    return secim if secim in DILLER else 'tr'


def kur(secim: str | None = None) -> str:
    global DIL
    DIL = secim if secim in DILLER else oku()
    return DIL


def yaz(secim: str) -> str:
    dosya().parent.mkdir(parents=True, exist_ok=True)
    dosya().write_text(secim + '\n')
    return kur(secim)


RENKLER = ('Gruvbox', 'Everforest', 'Rosé Pine', 'Tokyo Night', 'Dracula', 'Catppuccin Mocha')


def renk_dosyasi() -> Path:
    return ev() / 'arayuz-renk'


def renk_oku() -> str:
    secim = os.environ.get('CADRE_RENK', '').strip()
    if secim not in RENKLER:
        try:
            secim = renk_dosyasi().read_text().strip()
        except (OSError, UnicodeError):
            secim = ''
    return secim if secim in RENKLER else RENKLER[0]


def renk_yaz(secim: str) -> str:
    secim = secim if secim in RENKLER else RENKLER[0]
    renk_dosyasi().parent.mkdir(parents=True, exist_ok=True)
    renk_dosyasi().write_text(secim + '\n')
    return secim


def testleri_oku(home: Path | None = None) -> bool:
    try:
        return ((home or ev()) / 'arayuz-testler').read_text().strip() == '1'
    except (OSError, UnicodeError):
        return False


def testleri_yaz(goster: bool, home: Path | None = None) -> None:
    yol = (home or ev()) / 'arayuz-testler'
    yol.parent.mkdir(parents=True, exist_ok=True)
    yol.write_text('1\n' if goster else '0\n')


def t(metin: str, **degerler: object) -> str:
    duzenle = metin in EN
    if DIL == 'en':
        karsilik = EN.get(metin)
        if karsilik is None:
            EKSIK.add(metin)
        else:
            metin = TEKIL.get(metin, karsilik) if str(degerler.get('n', degerler.get('f'))) == '1' else karsilik
    ilk = metin.split(maxsplit=1)[0] if metin else ''
    if duzenle and len(ilk) > 1 and ilk[0].islower() and not any(c in ilk for c in '/\\._-=') and ilk not in ('git', 'cadre'):
        bas = 'İ' if DIL == 'tr' and metin[0] == 'i' else metin[0].upper()
        metin = bas + metin[1:]
    return metin.format(**degerler) if degerler else metin


